import assert from 'node:assert/strict';
import fs from 'node:fs';
import {validateDraft,readProject,projectJSON,lua} from '../lib/workbench.ts';
const c=JSON.parse(fs.readFileSync(new URL('../public/unit-catalog.json',import.meta.url),'utf8'));
assert.equal(c.units.length,453);
assert.deepEqual(validateDraft(c,{}),[]);
const edits=validateDraft(c,{'204:health':'350','204:weapon-0-reload':'2'});
const output=lua(c,edits,'QA\nnot-code');
assert.match(output,/value\s*=\s*350000/);
assert.match(output,/value\s*=\s*2000/);
assert.ok(output.includes('attack.f_updateCachedData()'));
assert.ok(output.includes('root.f_recreateModifiedUnitTypes()'));
assert.deepEqual(readProject(projectJSON(c,edits,'QA'),c).edits,edits);
for(const value of ['', 'Infinity','NaN','-1','1.00001'])assert.throws(()=>validateDraft(c,{'204:health':value}));
assert.throws(()=>validateDraft(c,{'204:fake.path':'10'}));
assert.throws(()=>validateDraft(c,{'204:weapon-0-range-max':'300'}));
assert.equal(validateDraft(c,{'204:weapon-0-range-max':'300','204:weapon-0-range-stop':'310'}).length,2);
const project=JSON.parse(projectJSON(c,edits,'QA'));
assert.throws(()=>readProject(JSON.stringify({...project,path:'evil'}),c));
assert.throws(()=>readProject(JSON.stringify({...project,sourceSha256:'0'.repeat(64)}),c));
assert.throws(()=>readProject(JSON.stringify({...project,edits:[edits[0],edits[0]]}),c));
assert.deepEqual(validateDraft(c,{'204:health':'200'}),[]);
console.log('PASS catalog, changed-only Lua, JSON roundtrip, numeric/path/import/range guards (18 assertions)');

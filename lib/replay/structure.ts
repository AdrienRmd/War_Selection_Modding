/** Structures de sortie du parser de replay — port typé de
 *  replayStructure.js (IbubussI / wsunitstats-static). */
import type { DatasetContainer, TimeLineEvent } from "./dataset";

export interface Match {
  startTime?: number;
  /** Durée en ms. */
  duration: number;
  /** Clé de type de match (replayMatchType*). */
  mode: string;
  winnerTeams: number[];
  playersCount: number;
  factionsCount: number;
  region?: string;
  gameVersion?: string;
  matchSeed?: number;
  isMatchmaking: boolean;
  creator?: string;
  isDevMode: boolean;
  isComplete: boolean;
  isWonderWin: boolean;
  replayCode: string;
  isMapGen?: unknown;
  isMapReleased?: boolean;
  mapCode?: string;
  /** Clé de symétrie (replaySymmetryType*). */
  mapSymmetry?: string;
}

export interface Team {
  id: number;
  factions: number[];
  players: number[];
  isWinner: boolean;
  isPlayerTeam: boolean;
  color: { dark: string; light: string };
}

export interface PlayerResearch {
  id: number;
  takenTime: number;
}

export interface PlayerUnitStat {
  /** gameId d'unité du contexte de jeu (ex. « WarSelection/3/ew/knight »). */
  id: string;
  number: number;
  points?: number;
}

export interface Player {
  id: number;
  /** Hypothèse du format : un joueur ne contrôle qu'une faction. */
  factionId: number;
  nickname: string;
  isNicknameAutogenerated: boolean;
  rating?: number;
  team?: number;
  group?: number;
  survivalTime?: number;
  isWinner: boolean;
  isDead?: boolean;
  color: string;
  researches?: PlayerResearch[];
  isWonderBuilt?: boolean;
  isWonderWin?: boolean;
  lastAgeResearch?: number;
  unitsCreated?: Map<string, PlayerUnitStat[]>;
  unitsKilledByFaction?: Array<{ factionId: number; name: string | null; units: Map<string, PlayerUnitStat[]> }>;
  unitsKilledPlain?: Map<string, PlayerUnitStat[]>;
  unitsLostByFaction?: Array<{ name: string | null; units: Map<string, PlayerUnitStat[]> }>;
  unitsLostPlain?: Map<string, PlayerUnitStat[]>;
  firstWonderTime?: number;
  unitsLostOn: boolean;
  mvpScore?: number;
  isMvp?: boolean;
  unitsCreatedOn: number;
  researchOn: boolean;
  survivalOn: boolean;
  unitsKilledOn: boolean;
}

export interface ReplayParseSuccess {
  error: 0;
  match: Match;
  teams: Team[];
  players: Player[];
  charts: DatasetContainer[];
  timeLinePeriod: number;
  message?: undefined;
}

export interface ReplayParseFailure {
  error: number;
  message: string;
  match?: undefined;
  teams?: undefined;
  players?: undefined;
  charts?: undefined;
  timeLinePeriod?: undefined;
}

export type ReplayParseResult = ReplayParseSuccess | ReplayParseFailure;

/** Guard de discrimination du résultat (error:0 n'est pas suffisant pour TS). */
export function isReplaySuccess(
  result: ReplayParseResult,
): result is ReplayParseSuccess {
  return result.error === 0 && "match" in result;
}

export const MATCH_TYPES: ReadonlyMap<number, string> = new Map([
  [0, "replayMatchTypeFFA"],
  [1, "replayMatchTypeTeamMatch"],
  [2, "replayMatchTypeArmageddon"],
  [3, "replayMatchTypeSurvival"],
  [4, "replayMatchTypeRank1"],
  [5, "replayMatchTypeRank2"],
  [6, "replayMatchTypeSandbox"],
  [7, "replayMatchTypeTOW"],
  [8, "replayMatchTypeCustom"],
  [9, "replayMatchTypeMafia"],
  [255, "replayMatchTypeUndef"],
]);

export function matchTypeFromId(id: number): string {
  return MATCH_TYPES.get(id) ?? MATCH_TYPES.get(255)!;
}

export const SYMMETRY_TYPES: ReadonlyMap<number, string> = new Map([
  [0, "replaySymmetryTypeNo"],
  [1, "replaySymmetryTypeVertical"],
  [2, "replaySymmetryTypeVerticalFlipped"],
  [3, "replaySymmetryTypeHorizontal"],
  [4, "replaySymmetryTypeHorizontalFlipped"],
  [5, "replaySymmetryTypeDiagonal"],
  [6, "replaySymmetryTypeDiagonalReverse"],
  [7, "replaySymmetryTypeRandom"],
]);

export function symmetryTypeFromId(id: number | undefined): string {
  if (id === undefined) return SYMMETRY_TYPES.get(0)!;
  return SYMMETRY_TYPES.get(id) ?? SYMMETRY_TYPES.get(0)!;
}


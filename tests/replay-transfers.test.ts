const period = 30000;

function fakePlayers(n: number): Player[] {
  return Array.from({ length: n }, (_, i) => ({
    id: i,
    factionId: i,
    nickname: `P${i}`,
    isNicknameAutogenerated: false,
    isWinner: false,
    color: "#fff",
    unitsLostOn: false,
    unitsCreatedOn: 0,
    researchOn: false,
    survivalOn: false,
    unitsKilledOn: false,
  }));
}

function fakeTeams(teamA: number[], teamB: number[]): Team[] {
  const mk = (id: number, players: number[]): Team => ({
    id,
    factions: players,
    players,
    isWinner: false,
    isPlayerTeam: true,
    color: { dark: "#000", light: "#fff" },
  });
  return [mk(0, teamA), mk(1, teamB)];
}

/** Conteneur multi-lignes avec une série par joueur (3 lignes). */
function multiRowContainer(
  prefix: string,
  rowsByPlayer: number[][][],
  playerNames: string[],
): DatasetContainer {
  const container = new DatasetContainer(prefix);
  const group = new DatasetGroup("replayDatasetGroupPlayers", "players");
  rowsByPlayer.forEach((rows, i) => {
    const ds = new TimeLineMultiRowDataset(
      playerNames[i] ?? `P${i}`,
      false,
      null,
      "timeout",
      3,
      rows.length,
    );
    ds.values = rows;
    group.addDataset(ds);
  });
  container.addDatasetGroup(group);
  return container;
}

/** Revenu moteur arbitraire (10 k) par période — stable pour tous les tests.
 *  Déduit cumul récolté / stock courant d'une série de resSpent souhaitée :
 *  now_j = now_{j−1} + revenu − spent_j (reconstruction inverse du calcul
 *  réel resSpent = Δcumul − Δstock). */
const SYNTH_INCOME = 10;

function spentToCollectedNow(spentByPlayer: number[][][]): {
  collected: number[][][];
  now: number[][][];
} {
  const collected: number[][][] = [];
  const now: number[][][] = [];
  for (const spent of spentByPlayer) {
    // Sortie TRANSPOSÉE comme le vrai dataset : [ressource][période].
    const col: number[][] = [[], [], []];
    const stk: number[][] = [[], [], []];
    let c = [0, 0, 0];
    let s = [100, 100, 100]; // stock initial (période 0, ignorée par l'algo)
    for (let j = 0; j < spent.length; j++) {
      c = [c[0] + SYNTH_INCOME, c[1] + SYNTH_INCOME, c[2] + SYNTH_INCOME];
      s = [s[0] + SYNTH_INCOME - spent[j][0], s[1] + SYNTH_INCOME - spent[j][1], s[2] + SYNTH_INCOME - spent[j][2]];
      for (let k = 0; k < 3; k++) {
        col[k].push(c[k]);
        stk[k].push(s[k]);
      }
    }
    collected.push(col);
    now.push(stk);
  }
  return { collected, now };
}

function fakeReplay(
  players: Player[],
  teams: Team[],
  spentByPlayer: number[][][],
  researchesByPlayer?: Map<number, Array<{ id: number; takenTime: number }>>,
): ReplayParseSuccess {
  const p = players.map((x) => ({
    ...x,
    researches: researchesByPlayer?.get(x.id) ?? [],
  })) as Player[];
  const { collected, now } = spentToCollectedNow(spentByPlayer);
  const names = p.map((x) => x.nickname);
  return {
    error: 0,
    match: {
      duration: 10 * 60_000,
      mode: "replayMatchTypeTeamMatch",
      winnerTeams: [0],
      playersCount: p.length,
      factionsCount: p.length,
      isMatchmaking: true,
      isDevMode: false,
      isComplete: true,
      isWonderWin: false,
      replayCode: "SYNTHETIC000",
    },
    teams,
    players: p,
    charts: [
      multiRowContainer("replayDatasetResourcesCollected", collected, names),
      multiRowContainer("replayDatasetResourcesNow", now, names),
    ],
    timeLinePeriod: period,
  } satisfies ReplayParseSuccess;
}

